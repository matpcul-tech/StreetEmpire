import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { prune, dedup, resample, quantize, meshopt } from '@gltf-transform/functions';
import { MeshoptEncoder } from 'meshoptimizer';
await MeshoptEncoder.ready;
const keep = new Set(['Idle_Loop','Walk_Loop','Jog_Fwd_Loop','Sprint_Loop','Punch_Jab','Punch_Cross','Death01','Hit_Chest','Driving_Loop']);
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.encoder': MeshoptEncoder });
const doc = await io.read('AnimationLibrary_Godot_Standard.gltf');
for (const a of doc.getRoot().listAnimations()) if (!keep.has(a.getName())) a.dispose();
await doc.transform(resample(), prune(), dedup(), quantize(), meshopt({ encoder: MeshoptEncoder, level: 'medium' }));
await io.write('/workspace/street-game/public/models/mannequin.glb', doc);
